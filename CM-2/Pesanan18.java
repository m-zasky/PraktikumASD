public class Pesanan18 {
    int kodePesanan; // kode unik item pesanan
    String namaPesanan; // nama makanan atau minuman yang dipesan
    int harga; // harga satuan
    String namaPembeli; // nama pembeli yang melakukan pesanan

    public Pesanan18(int kodePesanan, String namaPesanan, int harga, String namaPembeli) {
        this.kodePesanan = kodePesanan;
        this.namaPesanan = namaPesanan;
        this.harga = harga;
        this.namaPembeli = namaPembeli;
    }
}